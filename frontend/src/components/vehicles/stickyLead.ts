'use client';
import { useCallback, useEffect, useRef, useState } from 'react';

// ── عمودان ثابتان في أوّل الجدول: الإجراءات، ثمّ رقم اللوحة ──────────────────
//
// جداولُ قسم المركبات أعرضُ من الشاشة — سبعةٌ وأربعون عمودًا في سجل المركبات،
// وعشرةٌ أو أكثر في كلّ صفحةِ عائلة. وكانت أزرارُ التعديل والحذف آخرَ عمود:
// من أراد تعديلَ صفٍّ يراه أمامه لزمه أن يمرّر عرضًا إلى آخر الجدول، ثم يمرّر
// راجعًا ليتأكّد أنّه ما زال على الصفّ نفسِه. وهي رحلةٌ تُقطَع لكلّ صفّ،
// ويُخطأ فيها الصفُّ عند أوّل انزلاقٍ سطرًا أثناء التمرير — فيُحذَف غيرُ
// المقصود. فصارت الإجراءاتُ أوّلَ ما يُقرأ، وثابتةً مهما مُرِّر.
//
// ── ولماذا اللوحةُ معها ─────────────────────────────────────────────────────
// تثبيتُ الإجراءات وحدَها حلَّ نصفَ المشكلة: الأزرارُ حاضرةٌ دائمًا، لكنّ
// السطرَ الذي تعمل عليه يصير مجهولًا بعد عمودين من التمرير. تقرأ تاريخَ فحصٍ
// أو رقمَ وثيقةٍ في آخر الجدول ولا شيءَ على الشاشة يقول لأيّ مركبةٍ هو. واللوحةُ
// هي هويّةُ الصفّ — بها يُعرَف، وبها يُبحَث عنه، وعليها يُضغط لفتحه.
// فتُثبَّت معها: يبقى «مَن هذه المركبة» و«ماذا أفعل بها» حاضرَين معًا.
//
// ── و`start` لا `left` ──────────────────────────────────────────────────────
// الجدولُ يُقرأ يمينًا إلى يسار في العربية ويسارًا إلى يمين في الإنجليزية،
// و`left-0` تثبّت العمودَ على الطرف الخطأ في إحداهما — أي فوق الأعمدة التي جاء
// ليجاورها. و`inset-inline-start` تتبع اتجاهَ الصفحة نفسِه فتصحّ في اللغتين.
//
// ── ولا بدّ للخليّة الثابتة من خلفيّةٍ صريحة ────────────────────────────────
// الخليّةُ الشفّافة تُرى من خلالها الأعمدةُ الجارية تحتها، فيصير العمودُ
// الثابتُ رُقعةً من نصَّين متراكبَين. ولهذا تحمل كلُّ خليّةٍ لونَ صفِّها
// و`group-hover` ليبقى تمييزُ الصفّ عند المرور عليه.

/** العمود الأوّل — الإجراءات. يُلصق بحافّة الجدول. */
export const LEAD = 'sticky start-0 z-20';

/** خلفيّةُ خليّةِ العمود الأوّل في صفٍّ عاديّ. */
export const LEAD_CELL = `${LEAD} bg-white group-hover:bg-slate-50`;

/**
 * العمود الثاني — اللوحة. موضعُه يُحسَب لا يُكتب: يُمرَّر `insetInlineStart`
 * في `style` بعرض عمود الإجراءات المقيس. والحدُّ الفاصل هنا لا هناك، فهو نهايةُ
 * المنطقة الثابتة كلِّها.
 */
export const LEAD_2 = 'sticky z-20 border-e border-slate-200';
export const LEAD_2_CELL = `${LEAD_2} bg-white group-hover:bg-slate-50`;

/**
 * ── عرضُ عمود الإجراءات يُقاس ولا يُفترَض ──────────────────────────────────
 *
 * لتثبيت عمودين متجاورين لا بدّ للثاني أن يعرف أين ينتهي الأوّل. ورقمٌ ثابتٌ
 * يُكتب بالتخمين يخطئ حتمًا: عمودُ الإجراءات يحمل في صفحةٍ زرَّ تجديدٍ بنصّه،
 * وفي أخرى «نزع الشريحة»، وفي ثالثةٍ أيقونتين — وعرضُه يتغيّر بتغيّر اللغة
 * وحدها. فيُقاس من الترويسة نفسِها، ويُعاد قياسُه كلّما تغيّر.
 *
 * ويُعاد الربطُ بمرجعٍ دالّة لا `useRef`: الجدولُ لا يُرسَم إلّا بعد التحميل،
 * فأثرٌ يقرأ `ref.current` مرّةً عند التركيب يجده فارغًا ولا يعود.
 */
export function useLeadOffset() {
  const [offset, setOffset] = useState(0);
  const obs = useRef<ResizeObserver | null>(null);

  const ref = useCallback((el: HTMLElement | null) => {
    obs.current?.disconnect();
    obs.current = null;
    if (!el) return;
    const measure = () => setOffset(el.getBoundingClientRect().width);
    measure();
    if (typeof ResizeObserver !== 'undefined') {
      obs.current = new ResizeObserver(measure);
      obs.current.observe(el);
    }
  }, []);

  useEffect(() => () => obs.current?.disconnect(), []);
  return { ref, offset };
}
