const MAP = { 'چ': 'ج', 'پ': 'ب', 'ڤ': 'ف', 'ک': 'ك', 'ی': 'ي', 'ۀ': 'ه' };
const arLetters = (s) => String(s ?? '').replace(/[چپڤکیۀ]/g, (c) => MAP[c] || c);
module.exports = { arLetters };
