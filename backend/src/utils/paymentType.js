/**
 * نوعُ الدفع — كيف يُقرَّر، ومَن يغلب مَن.
 *
 * ── ثلاثةُ مصادر، ترتيبُها هو القاعدة ────────────────────────────────────────
 *
 *  ① اليد. موظّفٌ اختار النوعَ على الكشف نفسِه، فلا يُغيَّر بعده تلقائيًّا أبدًا.
 *    والسببُ أنّ العميل الواحد «ممكن في حمولات يقولنا هنحاسبكوا عليها كاش
 *    وساعات ضريبي» — فالنوعُ واقعةٌ على الحمولة لا صفةٌ ثابتةٌ للعميل.
 *
 *  ② طريقةُ الدفع الآتيةُ من منصّة التشغيل. متى قالت `cash` فهو نقديٌّ ولو كان
 *    العميلُ ضريبيًّا — وهذا هو الاستثناء الوحيد الذي ينقض صفةَ العميل: العميلُ
 *    الضريبيُّ قد يدفع حمولةً بعينها نقدًا، والمنصّةُ تعرف ذلك لأنّها هي التي
 *    أخذت الطلب.
 *
 *  ③ صفةُ العميل من صفحة «أنواع الدفع». وهي الحالةُ العامّة: عميلُ الكاش يُحصَّل
 *    منه فورًا بلا فاتورة، والضريبيُّ تُكتب له فاتورةٌ ثمّ يُحصَّل بها.
 *
 * وما لا يُعرَف يبقى فارغًا: كشفٌ بلا عميلٍ معروفٍ ولا طريقةِ دفعٍ لا يُخمَّن له
 * نوع — والفارغُ يُقرأ «لم يُقرَّر بعد» ولا يصل قسمَ التحصيل أصلًا.
 */

/** هل تقول المنصّةُ إنّ هذه الحمولةَ نقديّة؟ */
const methodIsCash = (paymentMethod) => /^\s*cash\s*$/i.test(String(paymentMethod || ''));

/**
 * النوعُ المشتقُّ تلقائيًّا. لا يُنظَر هنا إلى ما على الكشف الآن — النداءُ هو
 * الذي يقرّر أيكتبه أم يترك اختيارَ اليد.
 *
 * @param {string} paymentMethod  «طريقة الدفع» كما جاءت من المنصّة
 * @param {string} customerType   نوعُ العميل: 'cash' | 'tax' | ''
 * @returns {'cash'|'tax'|''}
 */
const derivePaymentType = (paymentMethod, customerType) => {
  if (methodIsCash(paymentMethod)) return 'cash';
  const t = String(customerType || '').trim().toLowerCase();
  return t === 'cash' || t === 'tax' ? t : '';
};

/** أيُغيَّر هذا الكشفُ تلقائيًّا؟ لا، إن كان النوعُ مكتوبًا باليد. */
const mayAutoSet = (workflow) => String(workflow?.paymentTypeSource || '') !== 'manual';

module.exports = { derivePaymentType, methodIsCash, mayAutoSet };
